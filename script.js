function generateRoadmap() {

    const name = document.getElementById("name").value;
    const skill = document.getElementById("skill").value;
    const career = document.getElementById("career").value;

    if (name === "" || skill === "" || career === "") {
        alert("Please complete all fields.");
        return;
    }

    let careerName = "";
    let roadmap = [];

    if (career === "software") {

        careerName = "Software Engineer";

        roadmap = [
            "Java",
            "Python",
            "C++",
            "DSA",
            "SQL",
            "Git & GitHub"
        ];

    } else if (career === "data") {

        careerName = "Data Scientist";

        roadmap = [
            "Python",
            "SQL",
            "NumPy",
            "Pandas",
            "Statistics",
            "Machine Learning"
        ];

    } else if (career === "ml") {

        careerName = "Machine Learning Engineer";

        roadmap = [
            "Python",
            "NumPy",
            "Pandas",
            "Statistics",
            "Machine Learning",
            "Deep Learning"
        ];

    } else if (career === "web") {

        careerName = "Web Developer";

        roadmap = [
            "HTML",
            "CSS",
            "JavaScript",
            "Git & GitHub",
            "React",
            "Node.js",
            "SQL"
        ];

    } else if (career === "ai") {

        careerName = "AI Engineer";

        roadmap = [
            "Python",
            "Machine Learning",
            "Deep Learning",
            "AI"
        ];
    }

    const result = document.getElementById("roadmapResult");

    result.innerHTML = `
        <h2>🚀 ${name}'s ${careerName} Roadmap</h2>

        <p>Click any topic to view its complete syllabus.</p>

        <div class="roadmap-list">
            ${roadmap.map((topic, index) => `
                <div class="roadmap-item"
                     onclick="showSyllabus('${topic}')">

                    <span>${index + 1}. ${topic}</span>

                    <button>View Syllabus →</button>

                </div>
            `).join("")}
        </div>

        <div id="syllabusResult"></div>
    `;
}


function showSyllabus(topic) {

    const topics = syllabus[topic];

    const result = document.getElementById("syllabusResult");

    if (!topics) {
        result.innerHTML = `
            <div class="syllabus-card">
                <h2>${topic}</h2>
                <p>Syllabus will be added soon.</p>
            </div>
        `;
        return;
    }

    result.innerHTML = `
        <div class="syllabus-card">

            <h2>📚 ${topic} Complete Syllabus</h2>

            <p>Complete learning path for ${topic}</p>

            <div class="syllabus-list">

                ${topics.map((item, index) => `
                    <div class="syllabus-item">

                        <input type="checkbox"
                               id="${topic}-${index}">

                        <label for="${topic}-${index}">
                            ${index + 1}. ${item}
                        </label>

                    </div>
                `).join("")}

            </div>

        </div>
    `;
}